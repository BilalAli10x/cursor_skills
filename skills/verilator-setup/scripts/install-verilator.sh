#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Standalone Verilator v5.036 build-from-source. No Wally/CVA6 environment.
# Usage: WORKSPACE=/path/to/workspace bash install-verilator.sh
set -euo pipefail

VERILATOR_VERSION="${VERILATOR_VERSION:-v5.036}"
WORKSPACE="${WORKSPACE:-$(pwd)}"
PREFIX="${WORKSPACE}/tools/verilator"
SRC_DIR="${WORKSPACE}/tools/src/verilator"
JOBS="${JOBS:-$(nproc)}"
MARKER="# sle-skills verilator-setup"

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "error: missing command '$1' (install distro packages: git make autoconf gcc g++ flex bison help2man python3)" >&2
    exit 1
  }
}

for c in git make autoconf gcc g++ python3; do
  need_cmd "$c"
done

mkdir -p "${WORKSPACE}/tools/src" "${PREFIX}"

# Skip rebuild if this prefix already has the pinned version.
if [[ -x "${PREFIX}/bin/verilator" ]]; then
  have="$("${PREFIX}/bin/verilator" --version 2>/dev/null | awk '{print $2}' || true)"
  if [[ "${have}" == "${VERILATOR_VERSION#v}" || "v${have}" == "${VERILATOR_VERSION}" ]]; then
    echo "verilator ${have} already installed at ${PREFIX}"
  else
    echo "found verilator ${have:-unknown} at prefix; rebuilding ${VERILATOR_VERSION}"
    have=""
  fi
else
  have=""
fi

if [[ -z "${have:-}" ]]; then
  if [[ ! -d "${SRC_DIR}/.git" ]]; then
    git clone https://github.com/verilator/verilator.git "${SRC_DIR}"
  fi
  git -C "${SRC_DIR}" fetch --tags origin
  git -C "${SRC_DIR}" checkout "${VERILATOR_VERSION}"
  unset VERILATOR_ROOT
  (
    cd "${SRC_DIR}"
    autoconf
    ./configure --prefix="${PREFIX}"
    make -j"${JOBS}"
    make install
  )
fi

echo "${VERILATOR_VERSION}" > "${WORKSPACE}/tools/verilator.version"

gitignore="${WORKSPACE}/tools/.gitignore"
if [[ ! -f "${gitignore}" ]]; then
  printf '%s\n' \
    "# Installed tool prefixes and source clones (too large for git)." \
    "verilator/" \
    "riscv/" \
    "src/" > "${gitignore}"
else
  grep -qxF 'verilator/' "${gitignore}" || echo 'verilator/' >> "${gitignore}"
  grep -qxF 'src/' "${gitignore}" || echo 'src/' >> "${gitignore}"
fi

env_sh="${WORKSPACE}/tools/env.sh"
if [[ ! -f "${env_sh}" ]]; then
  cat > "${env_sh}" <<EOF
# Generated by sle-skills setup. Source from a shell:
#   source ${WORKSPACE}/tools/env.sh
EOF
fi
if ! grep -qF "${MARKER}" "${env_sh}"; then
  cat >> "${env_sh}" <<EOF

${MARKER}
export PATH="${PREFIX}/bin:\$PATH"
unset VERILATOR_ROOT
EOF
fi

readme="${WORKSPACE}/tools/README.md"
if [[ ! -f "${readme}" ]]; then
  cat > "${readme}" <<EOF
# tools/

Workspace tools installed by sle-skills.

    source ${WORKSPACE}/tools/env.sh

Installed prefixes are gitignored. Stamp files (\`*.version\`) are committed.
EOF
fi
if ! grep -qF "${MARKER}" "${readme}"; then
  cat >> "${readme}" <<EOF

${MARKER}
\`verilator-setup\` installs Verilator **${VERILATOR_VERSION}** to \`verilator/\`.

    source ${WORKSPACE}/tools/env.sh
    verilator --version
EOF
fi

# Idempotent bashrc PATH block.
BASHRC="${HOME}/.bashrc"
if [[ -f "${BASHRC}" ]] && grep -qF "${MARKER}" "${BASHRC}"; then
  echo "bashrc already contains verilator PATH block"
else
  {
    echo ""
    echo "${MARKER}"
    echo "if [ -x \"${PREFIX}/bin/verilator\" ]; then"
    echo "  export PATH=\"${PREFIX}/bin:\$PATH\""
    echo "  unset VERILATOR_ROOT"
    echo "fi"
  } >> "${BASHRC}"
  echo "appended PATH block to ${BASHRC}"
fi

export PATH="${PREFIX}/bin:${PATH}"
unset VERILATOR_ROOT
"${PREFIX}/bin/verilator" --version
echo "install complete: ${PREFIX}"
