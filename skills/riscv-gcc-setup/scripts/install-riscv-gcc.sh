#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Pinned official riscv64-unknown-elf-gcc (newlib ELF prebuilt). Do not compile GCC.
# Usage: WORKSPACE=/path/to/workspace bash install-riscv-gcc.sh
set -euo pipefail

TOOLCHAIN_TAG="${TOOLCHAIN_TAG:-2026.08.27}"
WORKSPACE="${WORKSPACE:-$(pwd)}"
PREFIX="${WORKSPACE}/tools/riscv"
GCC_BIN="${PREFIX}/bin/riscv64-unknown-elf-gcc"
MARKER="# sle-skills riscv-gcc-setup"
SRC_DIR="${WORKSPACE}/tools/src"

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "error: missing command '$1' (install distro packages: curl or wget, tar, xz-utils)" >&2
    exit 1
  }
}

need_cmd tar
if command -v curl >/dev/null 2>&1; then
  DOWNLOAD=(curl -fsSL -o)
elif command -v wget >/dev/null 2>&1; then
  DOWNLOAD=(wget -q -O)
else
  echo "error: missing command 'curl' or 'wget'" >&2
  exit 1
fi

arch="$(uname -m)"
if [[ "${arch}" != "x86_64" ]]; then
  echo "error: pinned prebuilt is Ubuntu x86_64 only (host is ${arch}). Do not compile GCC from source." >&2
  exit 1
fi

ubuntu="24.04"
if [[ -f /etc/os-release ]]; then
  # shellcheck disable=SC1091
  . /etc/os-release
  case "${VERSION_ID:-}" in
    22.04*) ubuntu="22.04" ;;
    *) ubuntu="24.04" ;;
  esac
fi

ASSET="riscv64-elf-ubuntu-${ubuntu}-gcc.tar.xz"
URL="https://github.com/riscv-collab/riscv-gnu-toolchain/releases/download/${TOOLCHAIN_TAG}/${ASSET}"

mkdir -p "${WORKSPACE}/tools" "${SRC_DIR}"

if [[ -x "${GCC_BIN}" ]]; then
  echo "riscv64-unknown-elf-gcc already installed at ${PREFIX}"
else
  tarball="${SRC_DIR}/${ASSET}"
  echo "downloading ${URL}"
  "${DOWNLOAD[@]}" "${tarball}" "${URL}"
  # Official nightly tarball is a top-level `riscv/` directory.
  tar -xJf "${tarball}" -C "${WORKSPACE}/tools"
  rm -f "${tarball}"
  if [[ ! -x "${GCC_BIN}" ]]; then
    echo "error: extract did not produce ${GCC_BIN}" >&2
    exit 1
  fi
fi

echo "${TOOLCHAIN_TAG}" > "${WORKSPACE}/tools/riscv-gcc.version"

gitignore="${WORKSPACE}/tools/.gitignore"
if [[ ! -f "${gitignore}" ]]; then
  printf '%s\n' \
    "# Installed tool prefixes and source clones (too large for git)." \
    "verilator/" \
    "riscv/" \
    "src/" > "${gitignore}"
else
  grep -qxF 'riscv/' "${gitignore}" || echo 'riscv/' >> "${gitignore}"
  grep -qxF 'src/' "${gitignore}" || echo 'src/' >> "${gitignore}"
fi

env_sh="${WORKSPACE}/tools/env.sh"
if [[ ! -f "${env_sh}" ]]; then
  cat > "${env_sh}" <<EOF
# Generated by sle-skills setup. Source from a shell:
#   source ${WORKSPACE}/tools/env.sh
EOF
fi
if ! grep -qF "${MARKER}" "${env_sh}"; then
  cat >> "${env_sh}" <<EOF

${MARKER}
export PATH="${PREFIX}/bin:\$PATH"
EOF
fi

readme="${WORKSPACE}/tools/README.md"
if [[ ! -f "${readme}" ]]; then
  cat > "${readme}" <<EOF
# tools/

Workspace tools installed by sle-skills.

    source ${WORKSPACE}/tools/env.sh

Installed prefixes are gitignored. Stamp files (\`*.version\`) are committed.
EOF
fi
if ! grep -qF "${MARKER}" "${readme}"; then
  cat >> "${readme}" <<EOF

${MARKER}
\`riscv-gcc-setup\` installs **riscv64-unknown-elf-gcc** from riscv-gnu-toolchain nightly **${TOOLCHAIN_TAG}** to \`riscv/\`.

    source ${WORKSPACE}/tools/env.sh
    riscv64-unknown-elf-gcc --version
EOF
fi

BASHRC="${HOME}/.bashrc"
if [[ -f "${BASHRC}" ]] && grep -qF "${MARKER}" "${BASHRC}"; then
  echo "bashrc already contains riscv-gcc PATH block"
else
  {
    echo ""
    echo "${MARKER}"
    echo "if [ -x \"${GCC_BIN}\" ]; then"
    echo "  export PATH=\"${PREFIX}/bin:\$PATH\""
    echo "fi"
  } >> "${BASHRC}"
  echo "appended PATH block to ${BASHRC}"
fi

export PATH="${PREFIX}/bin:${PATH}"
"${GCC_BIN}" --version
echo "install complete: ${PREFIX}"
